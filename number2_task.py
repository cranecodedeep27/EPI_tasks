# Строка больше 3 символов
string = input("Введите строку: ")

print(f"Общее количество символов в строке: {len(string)}")
print(f"Строка, повторённая 3 раза: {string * 3}")
print(f"Первый символ строки: {string[0]}")
print(f"Первые три символа строки: {string[:3]}")
print(f"Последние 3 символа строки: {string[-3:]}")
print(f"Строка в обратном порядке: {string[::-1]}")
print(f"Строка с удалённым первым и последним символом: {string[1:-1]}")